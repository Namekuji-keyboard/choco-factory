/** キーコードの日本語説明 */
export function keycodeDescriptionJa(k: Pick<Keycode, 'names' | 'comment'>): string {
  const n = k.names[0];
  if (/^[A-Z]$/.test(n)) return `英字 ${n} (Shift で大文字)`;
  let m = /^NUMBER_(\d)$/.exec(n);
  if (m) return `数字 ${m[1]}`;
  m = /^F(\d+)$/.exec(n);
  if (m) return `ファンクションキー F${m[1]}`;
  m = /^KP_NUMBER_(\d)$/.exec(n);
  if (m) return `テンキーの ${m[1]}`;
  if (SYMBOLS[n]) return SYMBOLS[n];
  if (BASIC[n]) return BASIC[n];
  if (INTERNATIONAL[n]) return INTERNATIONAL[n];
  if (CONSUMER[n]) return CONSUMER[n];
  m = /^C_MEDIA_(.+)$/.exec(n);
  if (m && MEDIA_SELECT[m[1]]) return `メディア選択: ${MEDIA_SELECT[m[1]]}`;
  m = /^C_AL_(.+)$/.exec(n);
  if (m && APP_LAUNCH[m[1]]) return `アプリ起動: ${APP_LAUNCH[m[1]]}`;
  m = /^C_AC_(.+)$/.exec(n);
  if (m && APP_CONTROL[m[1]]) return `アプリ操作: ${APP_CONTROL[m[1]]}`;
  return k.comment;
}
